    position[universe] = np.arange(universe.size)
    groups = {
        name: np.unique(np.concatenate([position[ntc[m]] for m in name.split("&")]))
        for name in dict.fromkeys(neg["grna_target"])
    }
    spec = cell["permutation_samplers"]["calibration"]
    sizes = sorted((len(c) for c in ntc.values()), reverse=True)
    assert spec["M"] == sum(sizes[: cell["calibration_group_size"]])
    ours = run_discovery_ntcells_complement(
        response[:, universe],
        gene_ids,
        X[universe],
        groups,
        neg[["response_id", "grna_target"]],
        B1=B1,
        B2=B2,
        B3=B3,
        side_code=cell["side_code"],
        resampling_mechanism="permutations",
        permutations=_replica(spec),
    )
    _compare(ours, cell["calibration_result"], p_exact=True)
