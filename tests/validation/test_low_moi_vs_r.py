@pytest.mark.parametrize("control_group", ["nt_cells", "complement"])
def test_calibration_on_rs_draws_is_rs_value_for_value(example, control_group):
    """With R's pairs and R's draws, the calibration check is R's, including the
    restriction to the NT cells and R's width rule for the shared draws."""
    e, response, gene_ids, X, targets, ntc = example
    cell = _grid(e, control_group, "permutations")
    neg = _frame(cell["negative_control_pairs"]).rename(columns={"grna_group": "grna_target"})
    n_cells = X.shape[0]
    universe = nt_cell_pool(ntc, n_cells) if control_group == "nt_cells" else np.arange(n_cells)
