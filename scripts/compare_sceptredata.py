def compare_run(run_dir: Path, n_jobs_list: list[int], pin: bool) -> dict:
    info = json.loads((run_dir / "run_info.json").read_text())
    e = load_export(run_dir / "export")
    settings = check_settings(e, info)
    alpha = settings["multiple_testing_alpha"]
    n_cells = settings["n_cells"]
    pool = (
        nt_cell_pool(e.ntc_grna_cells, n_cells) if settings["control_group"] == "nt_cells" else None
    )
    out: dict = {
        "settings": settings,
        "r_versions": info["versions"],
        "r_status": info["status"],
        "seed": SEED,
    }
    if pool is not None:
        same = bool(np.array_equal(pool, e.all_nt_idxs))
        out["nt_pool_equals_all_nt_idxs"] = same
        print(f"   NT pool from ntc_grna_cells == R's all_nt_idxs: {same} ({pool.size} cells)")
        if not same:
            raise SystemExit(
                "the NT pool is not R's all_nt_idxs; R's draws would index other cells"
            )

    r = {a: read_r(run_dir, a) for a in ANALYSES}
    out["pairwise_qc"] = {
        "discovery": discovery_pairwise_qc(e, r["discovery"], pool, settings),
        "calibration": calibration_pairwise_qc(e, r["calibration"], pool, settings),
    }

    # One untimed call first, so numba's compile cost is not charged to a timed analysis.
    timed(lambda: run_own("power", e, r["power"], settings, 1))

    analyses: dict = {}
    for a in ANALYSES:
        res: dict = {"wall_time_s": {}}
        frames = {}
        for n in n_jobs_list:
            frame, secs, caught = timed(lambda a=a, n=n: run_own(a, e, r[a], settings, n))
            frames[n] = frame
            res["wall_time_s"][f"pysceptre_n_jobs_{n}"] = secs
            if n == n_jobs_list[0]:
                res["warnings"] = caught
            print(f"   {a:<11} own RNG, n_jobs={n}: {secs:7.1f} s, {len(frame)} rows")
        res["wall_time_s"]["r"] = info["wall_time_s"][R_STEP[a]]
        first = frames[n_jobs_list[0]]
        res["n_jobs_results_identical"] = all(f.equals(first) for f in frames.values())
        tested = r_tested(r[a])
        m = merge(first, tested)
        res["r_rows"] = int(len(r[a]))
        res["r_tested"] = int(len(tested))
        res["merged"] = int(len(m))
        res["deterministic"] = deterministic_metrics(m)
        res["own_rng"] = {**p_agreement(m), **calls_metrics(a, m, alpha)}
        if a == "power":
            # Every positive control, including any that failed QC, which the power check
            # reports rather than drops.
            full = merge(first, r[a])
            res["pairwise_qc"] = qc_agreement(
                full["n_nonzero_trt_py"],
                full["n_nonzero_cntrl_py"],
                full["pass_qc_py"],
                full["n_nonzero_trt_r"],
                full["n_nonzero_cntrl_r"],
                full["pass_qc_r"],
            )
            res["pairwise_qc"]["pairs"] = int(len(r[a]))
            res["pairwise_qc"]["merged"] = int(len(full))
        analyses[a] = res

    if settings["resampling_mechanism"] == "permutations":
        specs = sampler_specs(e, settings, pool)
        out["r_sampler_specs"] = specs
        problems = check_specs_against_r(specs, info, pool)
        out["r_sampler_specs_match_run_info"] = not problems
        if problems:
            raise SystemExit("sampler sizing disagrees with run_info.json: " + "; ".join(problems))
        n_exact = max(n_jobs_list)
        draws = {"discovery": make_draws(specs["discovery"])}
        if pin:
            draws["calibration"] = make_draws(specs["calibration"])
            out["r_sampler_pin"] = pin_against_r(run_dir, draws)
            print(f"   replica pinned against R's own draws: {out['r_sampler_pin']}")
            if not all(v["all_equal"] for v in out["r_sampler_pin"].values()):
                raise SystemExit("the replica does not reproduce R's draws for this object")
        for a in ("discovery", "power", "calibration"):
            source = "calibration" if a == "calibration" else "discovery"
            if source not in draws:
                draws = {source: make_draws(specs[source])}
            frame, secs, caught = timed(
                lambda a=a, d=draws[source]: run_r_exact(a, e, r[a], settings, pool, d, n_exact)
            )
            m = merge(frame, r_tested(r[a]))
            analyses[a]["r_exact"] = {
                "n_jobs": n_exact,
                "wall_time_s": secs,
                "merged": int(len(m)),
                "warnings": caught,
                "deterministic": deterministic_metrics(m),
                **exact_p_metrics(m, alpha, SIDE_CODES[settings["side"]]),
            }
            ex = analyses[a]["r_exact"]
            print(
                f"   {a:<11} R's draws: {secs:7.1f} s, {ex['p_exactly_equal']}/{ex['n']} p-values "
                f"exactly equal, max rel diff {ex['p_max_rel_diff']:.3g}"
            )
        del draws
    out["analyses"] = analyses
    return out


