#!/usr/bin/env python3
"""Compare pysceptre with R sceptre on sceptredata's two real example screens.

    scripts/compare_sceptredata.py <dir> [<dir> ...] [--json PATH]
                                   [--n-jobs 1 8] [--pin-samplers]

A <dir> is one run written by `scripts/run_sceptredata_examples.R`, that is
`<out_dir>/<dataset>/<control_group>_<mechanism>/` holding `run_info.json`,
R's three result CSVs and `export/dataset.h5mu`, or that script's `<out_dir>`,
which stands for every run under it. The export comes from
`scripts/export_sceptre_dataset.R` followed by `scripts/make_h5mu.py`.

Both sides test the same pairs: discovery on R's `pass_qc` pairs, the power
check on every positive control R reports, and the calibration check on R's
negative control pairs with R's group size and QC thresholds. Four kinds of
comparison follow:

  deterministic  per-pair nonzero counts and `pass_qc` (every discovery pair,
                 the calibration pairs, the power check), fold change and
                 `z_orig`, none of which resampling enters
  own RNG        pysceptre's own draws at seed 0: p-value rank and log-scale
                 agreement, BH calls at R's alpha, calibration uniformity
  R's draws      permutation runs only: R's shared permutation draws,
                 regenerated by `tests/validation/r_samplers.py` and handed to
                 the low-level entry points with the cells in R's order, so
                 p-values compare value for value. Stage-2 p-values are also
                 checked against an independent evaluation of the skew-normal
                 tail at R's own fit (`stage_2_against_reference`), which says
                 which side is off when the two disagree
  wall time      pysceptre at each `--n-jobs`, next to R's from run_info.json

`--pin-samplers` first asks R for its own draws (sceptre's
`get_synthetic_permutation_idxs` on `sceptre_object.rds`) and checks the
replica against them over every draw: entry sum, position-weighted sum and a
few whole rows.

R's CSVs are read with `float_precision="round_trip"`; pandas' default parser
is off by a few ulp on them.

Results are merged into `--json` (default `<out_dir>/comparison.json`) under
`<dataset>/<run>`, and a summary is printed, ending in a Markdown table built
from everything in the JSON. The JSON is derived from real data, so it is
refused a path inside a git work tree that git does not ignore.
"""

