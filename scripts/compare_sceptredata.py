def source_digest() -> dict:
    """A SHA-256 over the code a comparison runs: the package, the loader and the replica.

    `git describe --dirty` cannot tell two uncommitted states apart; this can.
    Taken when the run starts, which is when the modules are imported.
    """
    package = Path(pysceptre.__file__).resolve().parent
    files = sorted(package.rglob("*.py")) + [
        REPO / "scripts" / "sceptre_io.py",
        REPO / "scripts" / "compare_sceptredata.py",
        REPO / "tests" / "validation" / "r_samplers.py",
    ]
    digest = hashlib.sha256()
    for f in files:
        digest.update(str(f.relative_to(REPO)).encode())
        digest.update(f.read_bytes())
    return {
        "sha256": digest.hexdigest(),
        "covers": "src/pysceptre/**/*.py, scripts/sceptre_io.py, "
        "scripts/compare_sceptredata.py, tests/validation/r_samplers.py",
        "n_files": len(files),
    }


def environment() -> dict:
    def git(*args):
        try:
            return subprocess.run(
                ["git", "-C", str(REPO), *args], capture_output=True, text=True, check=True
            ).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            return None

    try:
        import numba

        numba_version = numba.__version__
    except ImportError:
        numba_version = None
    return {
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        # The imported package and the commit it sits on; an editable install's
        # distribution metadata keeps the version it was installed at.
        "pysceptre_path": str(Path(pysceptre.__file__).resolve().parent),
        "pysceptre_dist_metadata": metadata.version("pysceptre"),
        "git": git("describe", "--always", "--dirty"),
        "source": source_digest(),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "machine": platform.machine(),
        "cpu_count": os.cpu_count(),
        "numpy": np.__version__,
        "scipy": metadata.version("scipy"),
        "pandas": pd.__version__,
        "numba": numba_version,
        "parallel_note": (
            "n_jobs > 1 uses threads off Linux; timings are wall clock on this machine, "
            "R's are from run_info.json (parallel = FALSE)"
        ),
    }


def refuse_unless_ignored(path: Path) -> None:
    """Refuse a path inside a git work tree that git does not ignore."""
    anchor = path.parent
    while not anchor.exists():
        anchor = anchor.parent
    inside = subprocess.run(
        ["git", "-C", str(anchor), "rev-parse", "--is-inside-work-tree"],
        capture_output=True,
        text=True,
    )
    if inside.returncode != 0 or inside.stdout.strip() != "true":
        return
    ignored = subprocess.run(["git", "-C", str(anchor), "check-ignore", "-q", str(path.resolve())])
    if ignored.returncode != 0:
        raise SystemExit(
            f"refusing to write {path}: it is inside a git work tree and not ignored, and the "
            "comparison is derived from real screen data"
        )


def _plain(x):
    """JSON-ready: plain Python types, and NaN or infinity as null."""
    if isinstance(x, dict):
        return {str(k): _plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple, np.ndarray)):
        return [_plain(v) for v in x]
    if isinstance(x, np.generic):
        x = x.item()
    if isinstance(x, float) and not np.isfinite(x):
        return None
    return x


def write_json(results: dict, path: Path) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(_plain(results), indent=2) + "\n")
    tmp.replace(path)


def _g(x, digits: int = 3) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    if isinstance(x, (int, np.integer)):
        return str(x)
    if x == 0:
        return "0"
    return f"{x:.{digits}g}"


def _calls(t: dict | None) -> str:
    if not t:
        return ""
    return f"{t['both']}/{t['pysceptre_only']}/{t['r_only']}/{t['neither']}"


def _qc_cell(q: dict | None) -> str:
    if not q:
        return ""
    n = q["pairs"]
    vals = (q["n_nonzero_trt_equal"], q["n_nonzero_cntrl_equal"], q["pass_qc_equal"])
    if all(v == n for v in vals):
        return f"{n}/{n} exact"
    return f"trt {vals[0]}/{n}, cntrl {vals[1]}/{n}, pass_qc {vals[2]}/{n}"


def _stage_2_cell(ex: dict | None) -> str:
    if not ex:
        return ""
    c = ex["stage_2_check"]
    if not c["stage_2"]:
        return "no stage 2"
    return (
        f"{c['within_rtol_of_r']}/{c['stage_2']} / {c['explained_by_r_tail_error']} / "
        f"{c['unexplained']}"
    )


def _py_wall(wall: dict) -> dict[int, float]:
    """pysceptre's wall times keyed by n_jobs, in n_jobs order."""
    prefix = "pysceptre_n_jobs_"
    found = {int(k[len(prefix) :]): v for k, v in wall.items() if k.startswith(prefix)}
    return dict(sorted(found.items()))


def markdown_table(results: dict) -> str:
    n_jobs_seen = sorted(
        {
            n
            for run in results.get("runs", {}).values()
            for res in run["analyses"].values()
            for n in _py_wall(res["wall_time_s"])
        }
    )
    head = [
        "run",
        "analysis",
        "pairs merged",
        "n_nonzero + pass_qc",
        "log2 FC r; max abs diff",
        "z max abs; max rel diff",
        "own RNG p: Spearman; Pearson -log10 p",
        "own RNG BH 2x2 both/py only/R only/neither",
        "R draws p: equal/n; max abs; max rel diff",
        "R draws stage 2: within 1e-6 of R / R tail error / unexplained",
        "R draws BH 2x2",
        "calibration KS py/R; false discoveries py/R",
        "power median log2 FC py/R",
        "wall s " + " / ".join(f"py n_jobs={n}" for n in n_jobs_seen) + " / R",
    ]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for key, run in sorted(results.get("runs", {}).items()):
        qc = run.get("pairwise_qc", {})
        for a in ANALYSES:
            res = run["analyses"][a]
            det, own = res["deterministic"], res["own_rng"]
            ex = res.get("r_exact")
            q = res.get("pairwise_qc") if a == "power" else qc.get(a)
            wall = res["wall_time_s"]
            py_wall = _py_wall(wall)
            py_times = " / ".join(_g(py_wall.get(n), 3) for n in n_jobs_seen)
            row = [
                key,
                a,
                f"{res['merged']}/{res['r_tested']}",
                _qc_cell(q),
                f"{_g(det['log2_fold_change_pearson_r'], 10)}; "
                f"{_g(det['log2_fold_change_max_abs_diff'])}",
                f"{_g(det['z_orig_max_abs_diff'])}; {_g(det['z_orig_max_rel_diff'])}"
                + (
                    f" ({det['z_orig_rel_diff_gt_1e-6']} pair > 1e-6)"
                    if det["z_orig_rel_diff_gt_1e-6"]
                    else ""
                ),
                f"{_g(own['spearman_rho'], 4)}; {_g(own['pearson_r_neg_log10_p'], 4)}",
                _calls(own.get("bh_2x2")),
                (
                    f"{ex['p_exactly_equal']}/{ex['n']}; {_g(ex['p_max_abs_diff'])}; "
                    f"{_g(ex['p_max_rel_diff'])}"
                )
                if ex
                else "",
                _stage_2_cell(ex),
                _calls(ex.get("bh_2x2")) if ex else "",
                (
                    f"{_g(own['ks_vs_uniform_py'])}/{_g(own['ks_vs_uniform_r'])}; "
                    f"{own['false_discoveries_py']}/{own['false_discoveries_r']}"
                )
                if a == "calibration"
                else "",
                (
                    f"{_g(own['median_log2_fold_change_py'], 4)}/"
                    f"{_g(own['median_log2_fold_change_r'], 4)}"
                )
                if a == "power"
                else "",
                f"{py_times} / {_g(wall['r'], 3)}",
            ]
            lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def print_run(key: str, run: dict) -> None:
    s = run["settings"]
    print(
        f"\n== {key}: {s['moi']} MOI, {s['control_group']}, {s['resampling_mechanism']}, "
        f"side={s['side']}, {s['n_genes']} genes x {s['n_cells']} cells"
    )
    qcs = {**run["pairwise_qc"], "power": run["analyses"]["power"].get("pairwise_qc")}
    for name, q in qcs.items():
        if q:
            print(f"   pairwise QC, {name}: {_qc_cell(q)} (R pass_qc {q['pass_qc_r']})")
    for a in ANALYSES:
        res = run["analyses"][a]
        own = res["own_rng"]
        print(
            f"   {a:<11} merged {res['merged']}/{res['r_tested']}, n_jobs identical "
            f"{res['n_jobs_results_identical']}, stages py {own['stage_counts_py']} "
            f"R {own['stage_counts_r']}"
        )
        if "bh_on_r_p_reproduces_r_significant" in own:
            print(
                f"      BH on R's p reproduces R's calls: {own['bh_on_r_p_reproduces_r_significant']}"
            )
        ex = res.get("r_exact")
        if ex:
            print(
                f"      R's draws: {ex['p_exactly_equal']}/{ex['n']} equal, stage agree "
                f"{ex['stage_agree']}, unequal by R stage {ex['unequal_by_r_stage']}, "
                f"max rel diff by stage "
                + ", ".join(
                    f"{k[6]}: {_g(ex[k])}"
                    for k in ex
                    if k.startswith("stage_") and k.endswith("rel_diff")
                )
            )
            c = ex["stage_2_check"]
            if c["stage_2"]:
                print(
                    f"      R's draws, stage 2: {c['within_rtol_of_r']}/{c['stage_2']} within "
                    f"{c['rtol']:g} of R; R off the reference on {c['r_off_reference']} "
                    f"(R p in {c['r_p_range_where_r_off_reference']}), explained "
                    f"{c['explained_by_r_tail_error']}, unexplained {c['unexplained']}; "
                    f"pysceptre max rel error vs reference {_g(c['max_rel_err_vs_reference_py'])}"
                )
        for det_name, det in (("own RNG", res["deterministic"]),) + (
            (("R's draws", ex["deterministic"]),) if ex else ()
        ):
            for row in det["z_orig_rel_diff_gt_1e-6_pairs"]:
                print(
                    f"      z_orig off by {row['rel_diff']:.3g} ({det_name}): "
                    f"{row['response_id']} / {row['grna_target']}, R {row['z_r']:.10g}, "
                    f"pysceptre {row['z_py']:.10g}"
                )
        for w in res.get("warnings", []):
            print(f"      warning x{w['count']}: {w['message'][:160]}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("dirs", nargs="+", type=Path)
    parser.add_argument("--json", type=Path, default=None)
    parser.add_argument("--n-jobs", type=int, nargs="+", default=[1, 8])
    parser.add_argument("--pin-samplers", action="store_true")
    args = parser.parse_args()

    runs = find_runs(args.dirs)
    out_path = args.json or (runs[0].parent.parent / "comparison.json")
    refuse_unless_ignored(out_path)
    results = json.loads(out_path.read_text()) if out_path.exists() else {}
    results.setdefault("runs", {})
    results["environment"] = environment()

    for run_dir in runs:
        key = run_key(run_dir)
        print(f"\n== {key}")
        start = time.perf_counter()
        results["runs"][key] = compare_run(run_dir, args.n_jobs, args.pin_samplers)
        results["runs"][key]["comparison_wall_time_s"] = time.perf_counter() - start
        write_json(results, out_path)

    for key, run in sorted(results["runs"].items()):
        print_run(key, run)
    table = markdown_table(results)
    results["markdown_table"] = table
    write_json(results, out_path)
    print("\n" + table)
    print(f"\nwrote {out_path}")
    return 0


