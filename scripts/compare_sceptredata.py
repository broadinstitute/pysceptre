def find_runs(paths: list[Path]) -> list[Path]:
    """Run directories: each given one, or every run under a given out_dir."""
    runs: list[Path] = []
    for path in paths:
        if (path / "run_info.json").exists():
            runs.append(path)
            continue
        found = sorted(p.parent for p in path.glob("*/*/run_info.json"))
        if not found:
            raise SystemExit(f"{path}: neither a run directory nor an out_dir holding runs")
        runs.extend(found)
    return runs


def run_key(run_dir: Path) -> str:
    return f"{run_dir.parent.name}/{run_dir.name}"


def read_r(run_dir: Path, analysis: str) -> pd.DataFrame:
    """R's whole result table, exactly as written."""
    return pd.read_csv(run_dir / CSV[analysis], float_precision="round_trip")


def r_tested(r: pd.DataFrame) -> pd.DataFrame:
    """R's rows that were tested, with `stage` and `significant` as plain types."""
    out = r[r["pass_qc"].astype(bool)].copy()
    out["stage"] = out["stage"].astype(int)
    if "significant" in out:
        out["significant"] = out["significant"].astype(bool)
    return out.reset_index(drop=True)


def check_settings(e, info: dict) -> dict:
    """The export's settings, checked against what R recorded for the run."""
    s = info["settings"]
    kwargs = e.analysis_kwargs()
    meta = e.metadata
    problems = []
    for k in ("moi", "control_group", "resampling_mechanism", "side"):
        if kwargs[k] != s[k]:
            problems.append(f"{k}: export {kwargs[k]!r}, R {s[k]!r}")
    for k in ("B1", "B2", "B3", "n_nonzero_trt_thresh", "n_nonzero_cntrl_thresh"):
        if meta[k] != s[k]:
            problems.append(f"{k}: export {meta[k]!r}, R {s[k]!r}")
    if meta["calibration_group_size"] != s["calibration_group_size"]:
        problems.append(
            f"calibration_group_size: export {meta['calibration_group_size']}, "
            f"R {s['calibration_group_size']}"
        )
    if e.covariate_matrix.shape[0] != s["n_cells_in_use"]:
        problems.append(f"cells: export {e.covariate_matrix.shape[0]}, R {s['n_cells_in_use']}")
    if list(meta["covariate_names"]) != list(s["covariate_matrix_columns"]):
        problems.append("covariate columns differ")
    if problems:
        raise SystemExit("export does not match the R run: " + "; ".join(problems))
    return {
        "moi": kwargs["moi"],
        "control_group": kwargs["control_group"],
        "resampling_mechanism": kwargs["resampling_mechanism"],
        "side": kwargs["side"],
        "resampling_approximation": kwargs.get("resampling_approximation", "skew_normal"),
        "multiple_testing_alpha": kwargs.get("multiple_testing_alpha", 0.1),
        "B1": meta["B1"],
        "B2": meta["B2"],
        "B3": meta["B3"],
        "n_nonzero_trt_thresh": meta["n_nonzero_trt_thresh"],
        "n_nonzero_cntrl_thresh": meta["n_nonzero_cntrl_thresh"],
        "calibration_group_size": s["calibration_group_size"],
        "n_genes": len(e.gene_ids),
        "n_cells": int(e.covariate_matrix.shape[0]),
        "n_covariates": int(e.covariate_matrix.shape[1]),
        "n_targets_with_cells": len(e.grna_target_cells),
        "n_ntc_grnas": len(e.ntc_grna_cells or {}),
    }


