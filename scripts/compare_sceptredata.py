def merge(py: pd.DataFrame, r: pd.DataFrame) -> pd.DataFrame:
    return r.merge(py, on=KEY, how="inner", suffixes=("_r", "_py"), validate="one_to_one")


def bh_calls(p, alpha: float) -> np.ndarray:
    """BH at `alpha`, as R's `p.adjust(method = "BH") < alpha`."""
    return stats.false_discovery_control(np.clip(np.asarray(p, dtype=float), 0, 1)) < alpha


def two_by_two(py: np.ndarray, r: np.ndarray) -> dict:
    py, r = np.asarray(py, dtype=bool), np.asarray(r, dtype=bool)
    return {
        "both": int((py & r).sum()),
        "pysceptre_only": int((py & ~r).sum()),
        "r_only": int((~py & r).sum()),
        "neither": int((~py & ~r).sum()),
    }


def _pearson(x, y) -> float:
    x, y = np.asarray(x, dtype=float), np.asarray(y, dtype=float)
    if x.size < 2 or np.ptp(x) == 0 or np.ptp(y) == 0:
        return float("nan")
    return float(stats.pearsonr(x, y).statistic)


def deterministic_metrics(m: pd.DataFrame, max_listed: int = 10) -> dict:
    """Fold change and `z_orig`: nothing resampled enters either.

    Pairs whose `z_orig` differs by more than 1e-6 relative are listed, since
    the maximum alone does not say whether one pair or many moved.
    """
    log2_py = np.log2(m["fold_change_py"].to_numpy(float))
    log2_r = m["log_2_fold_change"].to_numpy(float)
    z_py, z_r = m["z_orig_py"].to_numpy(float), m["z_orig_r"].to_numpy(float)
    dz = np.abs(z_py - z_r)
    rel = dz / np.maximum(np.abs(z_r), 1e-300)
    off = np.flatnonzero(rel > 1e-6)
    off = off[np.argsort(-rel[off])][:max_listed]
    return {
        "log2_fold_change_pearson_r": _pearson(log2_py, log2_r),
        "log2_fold_change_max_abs_diff": float(np.max(np.abs(log2_py - log2_r))),
        "log2_fold_change_abs_diff_gt_1e-9": int((np.abs(log2_py - log2_r) > 1e-9).sum()),
        "z_orig_max_abs_diff": float(dz.max()),
        "z_orig_max_rel_diff": float(rel.max()),
        "z_orig_rel_diff_gt_1e-6": int((rel > 1e-6).sum()),
        "z_orig_rel_diff_gt_1e-6_pairs": [
            {
                "response_id": m["response_id"].iloc[i],
                "grna_target": m["grna_target"].iloc[i],
                "z_r": float(z_r[i]),
                "z_py": float(z_py[i]),
                "rel_diff": float(rel[i]),
                "n_nonzero_trt": int(m["n_nonzero_trt"].iloc[i])
                if "n_nonzero_trt" in m
                else int(m["n_nonzero_trt_r"].iloc[i]),
            }
            for i in off
        ],
    }


# Relative agreement asked of a stage-2 p-value, against R or against the reference below.
SN_RTOL = 1e-6


def _log_left_tail(x: float, alpha: float) -> float:
    """log of the standard skew-normal CDF at `x`, without cancellation.

    `2 * integral of phi(t) Phi(alpha t)` up to `x`, with `phi(x)` and
    `Phi(alpha x)` factored out of the integrand. Evaluating the CDF as
    `Phi(x) - 2 T(x, alpha)` instead loses all relative precision once the
    result is many orders below `Phi(x)`, on the light side of the skew.
    """
    base = special.log_ndtr(alpha * x)

    def scaled(s):
        return np.exp(x * s - 0.5 * s * s + special.log_ndtr(alpha * (x - s)) - base)

    val, _ = integrate.quad(scaled, 0, np.inf, epsabs=0, epsrel=1e-13, limit=500)
    return math.log(2.0) - 0.5 * x * x - 0.5 * math.log(2 * math.pi) + base + math.log(val)


def skew_normal_reference_p(z: float, xi: float, omega: float, alpha: float, side_code: int):
    """The stage-2 p-value at the given fit, evaluated as `_log_left_tail` does.

    The tail follows the fit's median, standing in for the null median R
    compares `z` with; at stage 2 `z` lies far enough out that both agree.
    Floored at 1e-250 like both implementations.
    """
    x = (z - xi) / omega
    right = z >= skewnorm.median(alpha, loc=xi, scale=omega)
    if side_code == 1 or (side_code == 0 and right):
        log_p = _log_left_tail(-x, -alpha)
    else:
        log_p = _log_left_tail(x, alpha)
    return max(math.exp(log_p) * (2.0 if side_code == 0 else 1.0), 1e-250)


def stage_2_against_reference(m: pd.DataFrame, side_code: int) -> dict:
    """Stage-2 p-values on R's draws, against R and against an independent evaluation.

    Both sides fit the same skew normal to the same null statistics, so a
    disagreement can only come from evaluating its tail. Each pair is checked
    against R and against `skew_normal_reference_p` at R's own `xi`, `omega`,
    `alpha` and `z_orig`; a pair is explained when R is off the reference and
    pysceptre is on it.
    """
    s2 = m[m["stage_r"].to_numpy() == 2]
    if s2.empty:
        return {"stage_2": 0}
    ref = np.array(
        [
            skew_normal_reference_p(z, xi, om, al, side_code)
            for z, xi, om, al in zip(
                s2["z_orig_r"], s2["xi"], s2["omega"], s2["alpha"], strict=True
            )
        ]
    )
    p_py, p_r = s2["p_value_py"].to_numpy(float), s2["p_value_r"].to_numpy(float)
    vs_r = np.abs(p_py / p_r - 1)
    r_err = np.abs(p_r / ref - 1)
    py_err = np.abs(p_py / ref - 1)
    agree = vs_r <= SN_RTOL
    r_off = r_err > SN_RTOL
    explained = ~agree & r_off & (py_err <= SN_RTOL)
    r_ok = ~r_off
    return {
        "stage_2": int(len(s2)),
        "within_rtol_of_r": int(agree.sum()),
        "r_off_reference": int(r_off.sum()),
        "explained_by_r_tail_error": int(explained.sum()),
        "unexplained": int((~agree & ~explained).sum()),
        "max_rel_diff_where_r_on_reference": float(vs_r[r_ok].max()) if r_ok.any() else None,
        "max_rel_err_vs_reference_py": float(py_err.max()),
        "max_rel_err_vs_reference_r": float(r_err.max()),
        "r_p_range_where_r_off_reference": [float(p_r[r_off].min()), float(p_r[r_off].max())]
        if r_off.any()
        else None,
        "rtol": SN_RTOL,
    }


def p_agreement(m: pd.DataFrame) -> dict:
    p_py, p_r = m["p_value_py"].to_numpy(float), m["p_value_r"].to_numpy(float)
    return {
        "spearman_rho": float(stats.spearmanr(p_py, p_r).statistic) if len(m) > 1 else float("nan"),
        "pearson_r_neg_log10_p": _pearson(-np.log10(p_py), -np.log10(p_r)),
        "stage_agree": int((m["stage_py"].to_numpy() == m["stage_r"].to_numpy()).sum()),
        "stage_counts_py": stage_counts(m["stage_py"]),
        "stage_counts_r": stage_counts(m["stage_r"]),
    }


def stage_counts(stage: pd.Series) -> dict:
    return {str(int(k)): int(v) for k, v in stage.value_counts().sort_index().items()}


def calls_metrics(analysis: str, m: pd.DataFrame, alpha: float) -> dict:
    """BH calls against R's, and the calibration and power summaries."""
    out: dict = {}
    p_py, p_r = m["p_value_py"].to_numpy(float), m["p_value_r"].to_numpy(float)
    if "significant" in m:
        r_sig = m["significant"].to_numpy(bool)
        out["bh_on_r_p_reproduces_r_significant"] = bool(
            np.array_equal(bh_calls(p_r, alpha), r_sig)
        )
        py_sig = bh_calls(p_py, alpha)
        out["bh_2x2"] = two_by_two(py_sig, r_sig)
    if analysis == "calibration":
        out["ks_vs_uniform_py"] = float(stats.kstest(np.clip(p_py, 0, 1), "uniform").statistic)
        out["ks_vs_uniform_r"] = float(stats.kstest(np.clip(p_r, 0, 1), "uniform").statistic)
        out["false_discoveries_py"] = int(bh_calls(p_py, alpha).sum())
        out["false_discoveries_r"] = int(m["significant"].to_numpy(bool).sum())
    if analysis == "power":
        out["median_log2_fold_change_py"] = float(np.median(np.log2(m["fold_change_py"])))
        out["median_log2_fold_change_r"] = float(np.median(m["log_2_fold_change"]))
        out["median_p_py"] = float(np.median(p_py))
        out["median_p_r"] = float(np.median(p_r))
    return out


def exact_p_metrics(m: pd.DataFrame, alpha: float, side_code: int, max_listed: int = 25) -> dict:
    """Value-for-value agreement when both sides used the same draws."""
    p_py, p_r = m["p_value_py"].to_numpy(float), m["p_value_r"].to_numpy(float)
    diff = np.abs(p_py - p_r)
    rel = diff / np.maximum(np.abs(p_r), 1e-300)
    equal = p_py == p_r
    stage_r = m["stage_r"].to_numpy()
    stage_py = m["stage_py"].to_numpy()
    out = {
        "n": int(len(m)),
        "p_exactly_equal": int(equal.sum()),
        "p_max_abs_diff": float(diff.max()) if len(m) else float("nan"),
        "p_max_rel_diff": float(rel.max()) if len(m) else float("nan"),
        "stage_agree": int((stage_py == stage_r).sum()),
        "unequal_by_r_stage": {
            str(int(k)): int(v) for k, v in Counter(stage_r[~equal].tolist()).items()
        },
        "stage_1_or_3_unequal": int((~equal & (stage_r != 2)).sum()),
        "stage_counts_r": stage_counts(m["stage_r"]),
    }
    for stage in (1, 2, 3):
        sel = stage_r == stage
        if sel.any():
            out[f"stage_{stage}_max_rel_diff"] = float(rel[sel].max())
    out["stage_2_check"] = stage_2_against_reference(m, side_code)
    if "significant" in m:
        out["bh_2x2"] = two_by_two(bh_calls(p_py, alpha), m["significant"].to_numpy(bool))
    order = np.argsort(-rel)
    listed = [i for i in order if not equal[i]][:max_listed]
    cols = [c for c in ("xi", "omega", "alpha") if c in m]
    out["largest_differences"] = [
        {
            "response_id": m["response_id"].iloc[i],
            "grna_target": m["grna_target"].iloc[i],
            "stage_r": int(stage_r[i]),
            "stage_py": int(stage_py[i]),
            "p_r": float(p_r[i]),
            "p_py": float(p_py[i]),
            "rel_diff": float(rel[i]),
            **{f"r_{c}": float(m[c].iloc[i]) for c in cols},
        }
        for i in listed
    ]
    return out


def qc_agreement(trt, cntrl, passed, r_trt, r_cntrl, r_passed) -> dict:
    """Exact agreement of nonzero counts and `pass_qc` with R's, row for row."""
    r_passed = np.asarray(r_passed, dtype=bool)
    return {
        "pairs": int(r_passed.size),
        "n_nonzero_trt_equal": int((np.asarray(trt) == np.asarray(r_trt)).sum()),
        "n_nonzero_cntrl_equal": int((np.asarray(cntrl) == np.asarray(r_cntrl)).sum()),
        "pass_qc_equal": int((np.asarray(passed, dtype=bool) == r_passed).sum()),
        "pass_qc_r": int(r_passed.sum()),
    }


def _qc_against(r: pd.DataFrame, trt, cntrl, passed) -> dict:
    return qc_agreement(trt, cntrl, passed, r["n_nonzero_trt"], r["n_nonzero_cntrl"], r["pass_qc"])


def discovery_pairwise_qc(e, r: pd.DataFrame, pool, settings: dict) -> dict:
    """Nonzero counts for every discovery pair R listed, passing QC or not.

    A target QC left without cells is absent from the export; its pairs count
    zero treated cells, as in R.
    """
    targets = list(dict.fromkeys(r["grna_target"]))
    empty = np.empty(0, dtype=np.int64)
    cells = [np.asarray(e.grna_target_cells.get(t, empty), dtype=np.int64) for t in targets]
    trt, cntrl = nonzero_counts(
        e.response_matrix, cells, e.covariate_matrix.shape[0], control_cells=pool
    )
    rows = r["response_id"].map({g: i for i, g in enumerate(e.gene_ids)}).to_numpy()
    cols = r["grna_target"].map({t: j for j, t in enumerate(targets)}).to_numpy()
    t, c = trt[rows, cols], cntrl[rows, cols]
    passed = (t >= settings["n_nonzero_trt_thresh"]) & (c >= settings["n_nonzero_cntrl_thresh"])
    out = _qc_against(r, t, c, passed)
    out["targets_without_cells"] = [t for t in targets if t not in e.grna_target_cells]
    return out


def calibration_pairwise_qc(e, r: pd.DataFrame, pool, settings: dict) -> dict:
    """Nonzero counts for R's negative control pairs, within the calibration universe."""
    universe = calibration_universe(e, pool)
    groups = calibration_groups(e, r[KEY], universe)
    names = list(groups)
    response = e.response_matrix if pool is None else e.response_matrix[:, universe]
    trt, cntrl = nonzero_counts(response, [groups[n] for n in names], universe.size)
    rows = r["response_id"].map({g: i for i, g in enumerate(e.gene_ids)}).to_numpy()
    cols = r["grna_target"].map({n: j for j, n in enumerate(names)}).to_numpy()
    t, c = trt[rows, cols], cntrl[rows, cols]
    passed = (t >= settings["n_nonzero_trt_thresh"]) & (c >= settings["n_nonzero_cntrl_thresh"])
    out = _qc_against(r, t, c, passed)
    out["groups"] = len(names)
    return out


