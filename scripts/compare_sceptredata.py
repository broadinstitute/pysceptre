def timed(fn):
    """`fn()`, its wall time, and the warnings it raised, tallied by message."""
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        start = time.perf_counter()
        out = fn()
        elapsed = time.perf_counter() - start
    tally = Counter(str(w.message)[:400] for w in caught)
    return out, elapsed, [{"message": m, "count": c} for m, c in tally.items()]


def run_own(analysis: str, e, r: pd.DataFrame, settings: dict, n_jobs: int) -> pd.DataFrame:
    """One analysis through the public API, with pysceptre's own draws."""
    kwargs = e.analysis_kwargs()
    thresholds = dict(
        n_nonzero_trt_thresh=settings["n_nonzero_trt_thresh"],
        n_nonzero_cntrl_thresh=settings["n_nonzero_cntrl_thresh"],
    )
    if analysis == "discovery":
        pairs = r.loc[r["pass_qc"].astype(bool), KEY].reset_index(drop=True)
        return run_discovery_analysis(
            e.response_matrix,
            e.gene_ids,
            e.covariate_matrix,
            e.grna_target_cells,
            pairs,
            **kwargs,
            seed=SEED,
            n_jobs=n_jobs,
        )
    if analysis == "power":
        return run_power_check(
            e.response_matrix,
            e.gene_ids,
            e.covariate_matrix,
            e.grna_target_cells,
            positive_control_pairs=r[KEY].reset_index(drop=True),
            **thresholds,
            **kwargs,
            seed=SEED,
            n_jobs=n_jobs,
        )
    kwargs.pop("ntc_grna_cells", None)
    pairs = r[KEY].reset_index(drop=True)
    return run_calibration_check(
        e.response_matrix,
        e.gene_ids,
        e.covariate_matrix,
        e.ntc_grna_cells,
        n_calibration_pairs=len(pairs),
        calibration_group_size=settings["calibration_group_size"],
        negative_control_pairs=pairs,
        **thresholds,
        **kwargs,
        seed=SEED,
        n_jobs=n_jobs,
    )


def calibration_universe(e, pool: np.ndarray | None) -> np.ndarray:
    """The cells a calibration check runs on: the NT pool, or every cell."""
    return pool if pool is not None else np.arange(e.covariate_matrix.shape[0])


def calibration_groups(e, pairs: pd.DataFrame, universe: np.ndarray) -> dict[str, np.ndarray]:
    """Each synthetic group's cells, as positions in `universe`."""
    n_cells = e.covariate_matrix.shape[0]
    position = np.full(n_cells, -1, dtype=np.int64)
    position[universe] = np.arange(universe.size)
    ntc = {g: position[np.asarray(c, dtype=np.int64)] for g, c in e.ntc_grna_cells.items()}
    return negative_control_pairs_from_names(pairs, ntc, universe.size)


def sampler_specs(e, settings: dict, pool: np.ndarray | None) -> dict:
    """R's shared permutation sampler calls, sized from the export.

    `discovery` serves discovery and the power check; `calibration` the
    calibration check. Both follow sceptre's `get_synthetic_permutation_idxs`.
    """
    B = settings["B1"] + settings["B2"] + settings["B3"]
    sizes = [len(c) for c in e.grna_target_cells.values() if len(c)]
    nt_sizes = sorted((len(c) for c in e.ntc_grna_cells.values() if len(c)), reverse=True)
    width = int(sum(nt_sizes[: settings["calibration_group_size"]]))
    if pool is None:
        n = settings["n_cells"]
        discovery = {"sampler": "fisher_yates", "n_tot": n, "M": max(sizes), "B": B}
        calibration = {"sampler": "fisher_yates", "n_tot": n, "M": width, "B": B}
    else:
        discovery = {
            "sampler": "hybrid_fisher_iwor",
            "N": int(pool.size),
            "m": min(sizes),
            "M": max(sizes),
            "B": B,
        }
        calibration = {"sampler": "fisher_yates", "n_tot": int(pool.size), "M": width, "B": B}
    return {"discovery": discovery, "calibration": calibration}


def check_specs_against_r(specs: dict, info: dict, pool: np.ndarray | None) -> list[str]:
    """Where the derived sizing disagrees with the sizes R recorded for the run."""
    s = info["settings"]
    problems = []
    disc = specs["discovery"]
    lo, hi = s["grna_group_n_cells_range"]
    if disc["M"] != hi or (pool is not None and disc["m"] != lo):
        problems.append(f"target size range {disc.get('m')}..{disc['M']}, R {lo}..{hi}")
    if pool is not None and pool.size != s["n_nt_cells"]:
        problems.append(f"NT pool {pool.size} cells, R {s['n_nt_cells']}")
    nt_sizes = sorted(s["indiv_nt_grna_n_cells"].values(), reverse=True)
    width = sum(nt_sizes[: s["calibration_group_size"]])
    if specs["calibration"]["M"] != width:
        problems.append(f"calibration width {specs['calibration']['M']}, R's sizes give {width}")
    return problems


def make_draws(spec: dict) -> np.ndarray:
    if spec["sampler"] == "fisher_yates":
        return fisher_yates_samlper(spec["n_tot"], spec["M"], spec["B"])
    return hybrid_fisher_iwor_sampler(spec["N"], spec["m"], spec["M"], spec["B"])


def pin_against_r(run_dir: Path, draws: dict[str, np.ndarray]) -> dict:
    """R's own draws for this object, against the replica, over every draw."""
    with tempfile.TemporaryDirectory() as tmp:
        script = Path(tmp) / "pin.R"
        script.write_text(_PIN_R)
        done = subprocess.run(
            [
                "Rscript",
                str(script),
                str(run_dir / "sceptre_object.rds"),
                ",".join(map(str, PINNED_DRAWS)),
            ],
            capture_output=True,
            text=True,
            check=True,
        )
    theirs = json.loads(done.stdout)
    out = {}
    for name, d in draws.items():
        r = theirs[name]
        weights = np.arange(1, d.shape[1] + 1, dtype=np.int64)
        rows = [i for i in PINNED_DRAWS if i < d.shape[0]]
        out[name] = {
            "shape_equal": [r["B"], r["width"]] == list(d.shape),
            "sum_entries_equal": int(r["sum_entries"]) == int(d.sum()),
            "sum_position_weighted_equal": int(r["sum_position_weighted"])
            == int((d * weights).sum()),
            "pinned_rows_equal": all(
                np.array_equal(d[i], np.asarray(row, dtype=np.int64))
                for i, row in zip(rows, r["pinned_rows"], strict=True)
            ),
        }
        out[name]["all_equal"] = all(out[name].values())
    return out


def run_r_exact(
    analysis: str, e, r: pd.DataFrame, settings: dict, pool, draws, n_jobs: int
) -> pd.DataFrame:
    """One analysis on R's own permutation draws, through the low-level entry points."""
    common = dict(
        B1=settings["B1"],
        B2=settings["B2"],
        B3=settings["B3"],
        fit_parametric_curve=settings["resampling_approximation"] == "skew_normal",
        side_code=SIDE_CODES[settings["side"]],
        seed=SEED,
        n_jobs=n_jobs,
        resampling_mechanism="permutations",
        permutations=draws,
    )
    pairs = r.loc[r["pass_qc"].astype(bool), KEY].reset_index(drop=True)
    if analysis in ("discovery", "power"):
        if pool is None:
            return run_discovery_ntcells_complement(
                e.response_matrix,
                e.gene_ids,
                e.covariate_matrix,
                e.grna_target_cells,
                pairs,
                **common,
            )
        return run_discovery_nt_cells(
            e.response_matrix,
            e.gene_ids,
            e.covariate_matrix,
            e.grna_target_cells,
            pool,
            pairs,
            **common,
        )
    universe = calibration_universe(e, pool)
    groups = calibration_groups(e, pairs, universe)
    response = e.response_matrix if pool is None else e.response_matrix[:, universe]
    return run_discovery_ntcells_complement(
        response, e.gene_ids, e.covariate_matrix[universe], groups, pairs, **common
    )


